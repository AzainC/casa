function inferRegion(name: string): string {
  const lower = name.toLowerCase();
  if (lower.includes('(sharjah)') || lower.includes('sharjah') || lower.includes('juwaiza') || lower.includes('shees')) return 'Sharjah';
  if (lower.includes('(ajman)') || lower.includes('ajman') || lower.includes('al jurf') || lower.includes('meshairef')) return 'Ajman';
  if (lower.includes('(abu dhabi)') || lower.includes('abu dhabi')) return 'Abu Dhabi';
  if (lower.includes('mina al arab') || lower.includes('julphar') || lower.includes('ras')) return 'Ras Al Khaimah';
  if (lower.includes('hatta')) return 'Dubai / Hatta';
  return 'Dubai';
}

