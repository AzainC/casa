const pad = (n: number) => String(n).padStart(2, '0');
const toDateStr = (d: Date) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

const getDynamicMockDate = (daysAgo: number) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return toDateStr(d);
};

const getDynamicTimestamp = (daysAgo: number, timeStr: string) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return `${toDateStr(d)}T${timeStr}+04:00`;
};

